export function whatsappShareURL(r: PanelResult): string {
  const lines: string[] = [
    `🛂 PANEL · Contract Review`,
    `Urgency: ${r.final_urgency_score}/10`,
    "",
    r.recommendation.tldr,
    "",
    "*What to do:*",
    ...r.recommendation.action_items.slice(0, 4).map((a) => `• ${a}`),
    "",
    "*Save offline:*",
    ...r.recommendation.contacts.map(
      (c) => `${c.name}${c.phone ? " · " + c.phone : ""}${c.whatsapp ? " · WA " + c.whatsapp : ""}`,
    ),
  ];
  return `https://wa.me/?text=${encodeURIComponent(lines.join("\n"))}`;
}

// ---------------------------------------------------------------------------
// Internals
// ---------------------------------------------------------------------------
function triggerDownload(content: string, filename: string, mime: string): void {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

function sectionHeading(
  doc: jsPDF,
  title: string,
  x: number,
  y: number,
  rgb: [number, number, number] = [100, 116, 139],
): number {
  doc.setFont("helvetica", "bold");
  doc.setFontSize(10);
  doc.setTextColor(...rgb);
  doc.text(title.toUpperCase(), x, y);
  doc.setDrawColor(...rgb);
  doc.setLineWidth(0.3);
  doc.line(x, y + 4, x + 18, y + 4);
  return y + 22;
}

function wrappedText(
  doc: jsPDF,
  text: string,
  x: number,
  y: number,
  maxWidth: number,
  lineHeight: number,
): number {
  const lines = doc.splitTextToSize(text, maxWidth);
  for (const line of lines) {
    doc.text(line, x, y);
    y += lineHeight;
  }
  return y;
}

function urgencyColorRGB(score: number): [number, number, number] {
  if (score >= 8) return [220, 38, 38];
  if (score >= 5) return [234, 88, 12];
  if (score >= 3) return [245, 158, 11];
  return [21, 128, 61];
}

function urgencyVerdict(score: number): string {
  if (score >= 8) return "Critical — act before signing";
  if (score >= 5) return "Elevated — significant concerns";
  if (score >= 3) return "Moderate — proceed with eyes open";
  return "Low — contract largely compliant";
}
